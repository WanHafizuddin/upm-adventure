export const GLYPH_W = 5;
export const GLYPH_H = 7;
const SPACE_W = 3;

/** Width in pixels of `text` at `scale`, with 1 px (× scale) between letters. */
export function textWidth(text: string, scale = 1): number {
  let w = 0;
  for (const ch of text.toUpperCase()) w += (ch === ' ' ? SPACE_W : GLYPH_W + 1) * scale;
  return Math.max(0, w - scale);
}

/** Draws `text` with its top-left at (x, y). Unknown characters are skipped. */
export function drawText(c: PixelCanvas, text: string, x: number, y: number, color: Rgb, scale = 1): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    if (ch === ' ') {
      cx += SPACE_W * scale;
      continue;
    }
    const glyph = GLYPHS[ch];
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row++) {
        for (let col = 0; col < GLYPH_W; col++) {
          if (glyph[row][col] === '#') c.rect(cx + col * scale, y + row * scale, scale, scale, color);
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
